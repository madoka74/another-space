def get(name):
    with urllib.request.urlopen(BASE + name, timeout=60) as r:
        return json.loads(r.read().decode('utf-8'))


def season(ra_deg, dec):
    if dec < -55:
        return '우리나라에서는 거의 볼 수 없는 남쪽 하늘'
    h = (ra_deg / 15) % 24
    if 2 <= h < 8:
        s = '겨울'
    elif 8 <= h < 14:
        s = '봄'
    elif 14 <= h < 20:
        s = '여름'
    else:
        s = '가을'
    if dec > 55:
        return f'{s} 저녁이 가장 좋고, 북쪽 하늘에서 거의 일 년 내내 보여요'
    if dec < -30:
        return f'{s} 저녁 남쪽 지평선 가까이 낮게'
    return f'{s} 저녁 하늘'


def main():
    cons = get('constellations.json')
    lines = get('constellations.lines.json')
    stars = get('stars.6.json')
    names = get('starnames.json')

    star_list = []
    for f in stars['features']:
        lon, lat = f['geometry']['coordinates']
        star_list.append((f['id'], (lon + 360) % 360, lat, f['properties']['mag'], f['properties'].get('bv', '0')))

    # 빠르게 찾기: 1도 칸
    grid = {}
    for s in star_list:
        grid.setdefault((int(s[1]), int(s[2] + 90)), []).append(s)

    def match(ra, dec):
        best, bd = None, 0.12
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                for s in grid.get(((int(ra) + dx) % 360, int(dec + 90) + dy), []):
                    d = math.hypot((s[1] - ra) * math.cos(math.radians(dec)), s[2] - dec)
                    if d < bd:
                        best, bd = s, d
        return best

    line_map = {}
    for f in lines['features']:
        line_map.setdefault(f['id'], []).extend(f['geometry']['coordinates'])
    out = []
    used = set()
    seen = set()
    for f in cons['features']:
        cid = f['id']
        if cid in seen:
            continue
        seen.add(cid)
        p = f['properties']
        ra0, dec0 = p['display'][0], p['display'][1]
        ra0 = (ra0 + 360) % 360
        polys = []
        for pl in line_map.get(cid, []):
            pts = []
            for lon, lat in pl:
                ra = (lon + 360) % 360
                s = match(ra, lat)
                mag = s[3] if s else 4.5
                nm = ''
                if s:
                    used.add(s[0])
                    n = names.get(str(s[0]), {})
                    nm = n.get('ko', '') or ''
                pts.append([round(ra, 3), round(lat, 3), round(mag, 2), nm])
            polys.append(pts)
        d = DETAIL.get(cid, {})
        out.append({'id': cid, 'ko': p.get('ko', p['name']), 'la': p['name'], 'ra': round(ra0, 2), 'dec': round(dec0, 2),
                    'season': season(ra0, dec0), 'text': TEXT.get(cid, ''), 'story': d.get('story', []), 'find': d.get('find', []),
                    'lines': polys})
    bg = [[round(s[1], 3), round(s[2], 3), round(s[3], 2), float(s[4] or 0)] for s in star_list if s[3] <= 4.8 and s[0] not in used]
    data = {'source': 'd3-celestial (c) 2015 Olaf Frohn, BSD-3-Clause — constellation lines, star catalog (Hipparcos-based), names',
            'constellations': out, 'stars': bg}
    with open(OUT, 'w', encoding='utf-8') as fp:
        json.dump(data, fp, ensure_ascii=False, separators=(',', ':'))
    print('별자리', len(out), '배경 별', len(bg), '크기', os.path.getsize(OUT))


if __name__ == '__main__':
    main()
